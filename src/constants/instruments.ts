/**
 * Dynamically resolves or synthesizes an InstrumentSpec for any user-typed symbol.
 * If symbol is 6 characters (e.g. "EURHUF" or "GBPSEK"), it derives base/quote,
 * standard pip size, and appropriate conversion logic.
 */
export function resolveInstrument(inputSymbol: string, fallbackCategory: InstrumentCategory = 'forex'): InstrumentSpec {
  const clean = inputSymbol.trim().toUpperCase().replace(/[^A-Z0-9_]/g, '');
  const mappedSymbol = DERIV_ALIASES[clean] || clean;
  const existing = INSTRUMENT_CATALOG.find((i) => i.symbol === mappedSymbol || i.symbol === clean);
  if (existing) return existing;

  // Synthesize for forex pair (6 chars, e.g. EURHUF)
  if (clean.length === 6 && /^[A-Z]{6}$/.test(clean)) {
    const base = clean.slice(0, 3);
    const quote = clean.slice(3, 6);
    const isJpy = quote === 'JPY';

    return {
      symbol: clean,
      name: `${base} / ${quote}`,
      category: 'forex',
      baseCurrency: base,
      quoteCurrency: quote,
      contractSize: 100000,
      tickSize: isJpy ? 0.001 : 0.00001,
      pipSize: isJpy ? 0.01 : 0.0001,
      tickValue: isJpy ? 100 : 1,
      defaultStopUnit: 'pips',
      supportedStopUnits: ['pips', 'price'],
      minLot: 0.01,
      lotStep: 0.01,
      maxLot: 100,
      defaultExchangeRate: isJpy ? 155.0 : 1.0,
      conversionPair: quote === 'USD' ? undefined : (isJpy ? 'USD/JPY' : `${quote}/USD`),
      conversionType: quote === 'USD' ? 'none' : 'divide_by_rate',
      isCustom: true,
      description: `Synthesized FX pair for ${clean}. Quote currency is ${quote}.`,
    };
  }

  // Fallback to custom template
  return {
    ...CUSTOM_INSTRUMENT_TEMPLATE,
    symbol: clean || 'CUSTOM',
    name: clean || 'Custom Instrument',
    category: fallbackCategory,
  };
}
